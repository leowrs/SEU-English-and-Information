-- 1. 查询选修“数据库”课程的女学生的学号、姓名及成绩。
SELECT 学生表.学号, 学生表.姓名, 学生选课表.成绩
FROM 学生表
INNER JOIN 学生选课表 ON 学生表.学号 = 学生选课表.学号
WHERE 学生选课表.课程名 = '数据库' AND 学生表.性别 = '女';

-- 2. 在学生表中插入一条新记录，然后查询每个学生的情况以及其所选课程号，要求新插入的学生也显示。
-- 插入新记录
INSERT INTO 学生表 (学号, 姓名, 性别, 系别)
VALUES ('20230007', '新学生', '男', '物理系');

-- 查询每个学生及其选修课程
SELECT 学生表.学号, 学生表.姓名, 学生选课表.课程名
FROM 学生表
LEFT JOIN 学生选课表 ON 学生表.学号 = 学生选课表.学号;
