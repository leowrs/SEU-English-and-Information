clear;
%重叠相加法
xe=rand(1,512);
n1=0:1:3;
xc1=n1;
n2=4:7;
xc2=8-n2;
xc=[xc1,xc2];
yn=zeros(1,519);
for j=0:7
xj=xe(64*j+1:64*(j+1));
xak=fft(xj,71);
xck=fft(xc,71);
yn1=ifft(xak.*xck); 
temp=zeros(1,519);
temp(64*j+1:64*j+71)=yn1;
yn=yn+temp;
end;
n=0:518;
figure(1);
subplot(2,1,1);
plot(n,yn);
xlabel('n');ylabel('y(n)');
title('重叠相加法');
subplot(2,1,2);
plot(n,abs(fft(yn)));
xlabel('k');ylabel('Y(k)');
axis([0,600,0,300]);
%重叠保留法
xe=rand(1,512);
k=1:7;
xe1=k-k;
xe_1=[xe1,xe];
yn_1=zeros(1,519);
for j=0:7
xj_1=xe_1(64*j+1:64*j+71);
xak_1=fft(xj_1);
xck_1=fft(xc,71);
yn1_1=ifft(xak_1.*xck_1);
temp_1=zeros(1,519);
temp_1(64*j+1:64*j+64)=yn1_1(8:71);
yn_1=yn_1+temp_1;
end;
n=0:518;
figure(2);
subplot(2,1,1);
plot(n,yn_1);
xlabel('n');ylabel('y(n)');
title('重叠保留法');
subplot(2,1,2);
plot(n,abs(fft(yn_1)));
xlabel('k');ylabel('Y(k)');
axis([0,600,0,300]);

