%Xa的自相关
clear;
figure(1);
N=16;
x=0:N-1;
p=8;
q=2;
y1=exp(-(x-p).^2/q);
n=0:N-1;
a=0.1;
f=0.0625;
y2=exp(-(a.*n)).*sin(2.*pi.*f.*n);
k=length(y1);
y3=fft(y1,2*k);
y4=fft(y2,2*k);
rm=real(ifft(conj(y4).*y4));
rm=[rm(k+2:2*k) rm(1:k)];
m=(-k+1):(k-1);
stem(m,rm);
