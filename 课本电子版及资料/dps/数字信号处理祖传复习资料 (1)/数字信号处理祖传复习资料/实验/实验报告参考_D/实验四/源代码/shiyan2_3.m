fc=1200;
fr=2000;
fs=8000;
Ap=0.5;
As=40;
wc=2*fs*tan(2*pi*fc/(2*fs));
wr=2*fs*tan(2*pi*fr/(2*fs));
%巴特沃斯
[N1,wn]=buttord(wc,wr,Ap,As,'s')
[num1,den1]=butter(N1,wn,'s')
[b1,a1]=bilinear(num1,den1,fs);
[h1,w]=freqz(b1,a1);
%切比雪夫
[N2,wn]=cheb1ord(wc,wr,Ap,As,'s')
[num2,den2]=cheby1(N2,Ap,wn,'s')
[b2,a2]=bilinear(num2,den2,fs);
[h2,w]=freqz(b2,a2);
%椭圆型
[N3,wn]=ellipord(wc,wr,Ap,As,'s')
[num3,den3]=ellip(N3,Ap,As,wn,'low','s')
[b3,a3]=bilinear(num3,den3,fs);
[h3,w]=freqz(b3,a3);

sys1=tf(b1,a1,1/8000)
sys2=tf(b2,a2,1/8000)
sys3=tf(b3,a3,1/8000)
f=w/pi*4000;
plot(f,20*log10(abs(h1)),':',f,20*log10(abs(h2)),'--',f,20*log10(abs(h3)),'-');
axis([0,3000,-100,10]);grid;
xlabel('频率/Hz'); ylabel('幅度/dB');
title('双线性变换法设计三种数字低通滤波器');
legend('巴特沃思数字低通滤波器','切比雪夫数字低通滤波器','椭圆数字低通滤波器');