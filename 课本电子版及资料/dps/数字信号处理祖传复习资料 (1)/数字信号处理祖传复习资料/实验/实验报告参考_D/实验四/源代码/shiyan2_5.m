fs=10000;
fr1=1000;
fr2=2000;
fc1=500;
fc2=3000;
Ap=3;
As=18;
%双线性变换法
wr1=2*fs*tan(2*pi*fr1/(2*fs));
wr2=2*fs*tan(2*pi*fr2/(2*fs));
wc1=2*fs*tan(2*pi*fc1/(2*fs));
wc2=2*fs*tan(2*pi*fc2/(2*fs));
[N,wn]=cheb1ord([wc1,wc2],[wr1,wr2],Ap,As,'s');
[num,den]=cheby1(N,Ap,wn,'stop','s');
[b,a]=bilinear(num,den,fs);
sys=tf(b,a,1/10000)
[h,w]=freqz(b,a);
fc2=w/pi*5000;
plot(fc2,20*log10(abs(h)));
axis([0,5000,-100,10]);grid;
xlabel('频率/Hz');
ylabel('幅度/dB');
title('双线性变换法设计切比雪夫数字带阻滤波器幅频响应');