%脉冲响应
wc1=2*pi*2000;
wc2=2*pi*3000;
wr2=2*pi*6000;
wr1=2*pi*1500;
rp=3;
rs1=5;
rs2=20;
fs=30000;
[n1,wn]=buttord([wc1,wc2],[wr1,wr2],rp,rs2,'s');
[B,A]=butter(n1,wn,'s');
[num1,den1]=impinvar(B,A,fs);
sys1=tf(num1,den1,1/30000)
[h1,w]=freqz(num1,den1);
f=w/pi*15000;
plot(f,20*log10(abs(h1)),'-.');
axis([500,7000,-50,10]);
grid;
hold on;
xlabel("频率/Hz");
ylabel("幅度/dB");

%双线性
wc11=2*fs*tan(wc1/(2*fs));
wc22=2*fs*tan(wc2/(2*fs));
wr11=2*fs*tan(wr1/(2*fs));
wr22=2*fs*tan(wr2/(2*fs));
[n2,wn]=buttord([wc11,wc22],[wr11,wr22],rp,rs2,'s');
[B,A]=butter(n2,wn,'s');
[num2,den2]=bilinear(B,A,fs);
sys2=tf(num2,den2,1/30000)
[h2,w]=freqz(num2,den2);
f=w/pi*15000;
plot(f,20*log10(abs(h2)),'-');
legend("脉冲响应不变法","双线性变换法");
