N1=15;
N2=45;
wc1=0.3;
wc2=0.5;
b1=fir1(N1,[wc1,wc2],hanning(N1+1));
b2=fir1(N2,[wc1,wc2],hanning(N2+1));
[h1,w1]=freqz(b1,1);
[h2,w2]=freqz(b2,1);
subplot(221);
plot(w1/pi,20*log10(abs(h1)));
grid;
xlabel('归一化频率');
ylabel('幅度/dB');
title('N1=15幅度特性');
subplot(222);
plot(w2/pi,20*log10(abs(h2)));
grid;
xlabel('归一化频率');
ylabel('幅度/dB');
title('N2=45幅度特性');
subplot(223);
plot(w1/pi,angle(h1));
grid;
xlabel('归一化频率');
ylabel('相位');
title('N1=15相位特性');
subplot(224);
plot(w2/pi,angle(h2));
grid;
xlabel('归一化频率');
ylabel('相位');
title('N2=45相位特性');