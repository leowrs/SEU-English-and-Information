N=16;
n=0:N-1;
xa=exp(-(n-8).^2/2);
xb=exp(-0.1*n).*sin(2*pi*0.0625*n);
k=length(xa);
%16点线性相关
%xa在前
subplot(411);
Xa=fft(xa,2*k);
Xb=fft(xb,2*k);
rm1=real(ifft(conj(Xb).*Xa));
rm1=[rm1(k+2:2*k),rm1(1:k)];
m1=(-k+1):(k-1);
stem(m1,rm1);
xlabel('m');
ylabel('幅度');
title('xa在前线性相关');
%xb在前
subplot(412);
rm2=real(ifft(conj(Xa).*Xb));
rm2=[rm2(k+2:2*k),rm2(1:k)];
m2=(-k+1):(k-1);
stem(m2,rm2);
xlabel('m');
ylabel('幅度');
title('xb在前线性相关');

%16点循环相关
%xa在前
subplot(413);
Xa3=fft(xa);
Xb3=fft(xb);
rm3=real(ifft(conj(Xb3).*Xa3));
m3=0:N-1;
stem(m3,rm3);
xlabel('m');
ylabel('幅度');
title('xa在前循环相关');
%xb在前
subplot(414);
rm4=real(ifft(conj(Xa3).*Xb3));
m4=0:N-1;
stem(m4,rm4);
xlabel('m');
ylabel('幅度');
title('xb在前循环相关');

