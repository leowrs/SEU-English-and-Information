N1=8;
n=0:N1-1;
M=512;
xe=randn(1,M);
N=N1+M-1;
c1=zeros(size(n));
c2=zeros(size(n));
c3=zeros(size(n));
for k=1:N1
    if n(k)<4&n(k)>=0;
        c1(k)=n(k);
    elseif n(k)<8&n(k)>=4;
        c2(k)=8-n(k);
    else 
        c3(k)=0;
    end
end
xc=c1+c2+c3;
%x2卷积前频谱
subplot(411);
Xe=fft(xe);
w=0:M-1;
stem(w,abs(Xe));
xlabel('w');
ylabel('幅度');
title('卷积前xe频谱');
%线性卷积
subplot(412);
xian=conv(xc,xe);
a1=0:N-1;
stem(a1,abs(fft(xian)));
title('线性卷积');
%重叠相加法
subplot(413);
