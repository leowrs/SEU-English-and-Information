%N=16
f1=1/16;
f2=1/64;
N=16;
n=0:N-1;
x1=sin(2*pi*0.125*n)+cos(2*pi*(0.125+f1)*n);
x2=sin(2*pi*0.125*n)+cos(2*pi*(0.125+f2)*n);
%时域
subplot(221);
stem(n,x1);
xlabel('n');
ylabel('x1');
title('f=1/16时x的时域波形')
subplot(223);
stem(n,x2);
xlabel('n');
ylabel('x2');
title('f=1/64时x的时域波形')
%频域
w=(0:N-1)/N;
X1=fft(x1,N);
X2=fft(x2,N);
subplot(222);
stem(w,abs(X1));
xlabel('w');
ylabel('幅度');
title('f=1/16时x的幅频特性')
subplot(224);
stem(w,abs(X2));
xlabel('w');
ylabel('幅度');
title('f=1/64时x的幅频特性')

