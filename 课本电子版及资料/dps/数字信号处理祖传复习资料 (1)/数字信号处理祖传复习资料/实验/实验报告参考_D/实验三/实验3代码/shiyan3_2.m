%（1）
figure(1);
a=0.1;
f1=0.0625;
f2=0.4375;
f3=0.5625;
n=0:15;
x1=exp(-a*n).*sin(2*pi*f1*n);
x2=exp(-a*n).*sin(2*pi*f2*n);
x3=exp(-a*n).*sin(2*pi*f3*n);
%时域波形
subplot(321);
stem(n,x1);
grid on;
xlabel('n');
ylabel('x1');
title('f=0.0625时x的时域波形');
subplot(323);
stem(n,x2);
grid on;
xlabel('n');
ylabel('x2');
title('f=0.4375时x的时域波形');
subplot(325);
stem(n,x3);
grid on;
xlabel('n');
ylabel('x3');
title('f=0.5625时x的时域波形');
%频域特性
l1=length(x1);
l2=length(x2);
l3=length(x3);
w1=(-l1/2:l1/2-1)/l1;
w2=(-l2/2:l2/2-1)/l2;
w3=(-l3/2:l3/2-1)/l3;
y1=fft(x1,l1);
y2=fft(x2,l2);
y3=fft(x3,l3);
Y1=fftshift(y1);
Y2=fftshift(y2);
Y3=fftshift(y3);
subplot(322);
plot(w1,abs(Y1));
grid on;
xlabel('w');
ylabel('幅度');
title('f=0.0625时x的频域特性');
subplot(324);
plot(w2,abs(Y2));
grid on;
xlabel('w');
ylabel('幅度');
title('f=0.4375时x的频域特性');
subplot(326);
plot(w3,abs(Y3));
grid on;
xlabel('w');
ylabel('幅度');
title('f=0.5625时x的频域特性');


