N=16;
n=0:N-1;
xa=exp(-(n-8).^2/2);
xb=exp(-0.1*n).*sin(2*pi*0.0625*n);
k=length(xa);
%自相关
subplot(211);
Xb=fft(xa,2*k);
rm2=real(ifft(conj(Xb).*Xb));
rm2=[rm2(k+2:2*k),rm2(1:k)];
m2=(-k+1):(k-1);
stem(m2,rm2);
xlabel('m');
ylabel('幅度');
title('xa自相关');
%自相关
subplot(212);
