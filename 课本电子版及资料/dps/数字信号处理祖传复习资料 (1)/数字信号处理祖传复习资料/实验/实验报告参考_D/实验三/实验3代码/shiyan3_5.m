N=16;
n=0:N-1;
x1=exp(-(n-8).^2/2);
x2=exp(-0.1*n).*sin(2*pi*0.0625*n);
%线性卷积
y1=conv(x1,x2);
n1=0:N+N-1-1;
subplot(211);
stem(n1,y1);
xlabel('n');
ylabel('y1');
title('线性卷积')
%循环卷积
X1=fft(x1);
X2=fft(x2);
X=X1.*X2;
y2=real(ifft(X));
n2=0:N-1;
subplot(212);
stem(n2,y2);
xlabel('n');
ylabel('y2');
title('循环卷积')
