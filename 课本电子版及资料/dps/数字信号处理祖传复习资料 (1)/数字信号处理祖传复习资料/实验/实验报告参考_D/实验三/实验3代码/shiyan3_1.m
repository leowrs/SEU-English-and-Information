n=0:15;
N=512;
x1=exp(-(n-8).^2/2);
x2=exp(-(n-8).^2/4);
x3=exp(-(n-8).^2/8);
w=0:N-1;
F1=fft(x1,N);
F2=fft(x2,N);
F3=fft(x3,N);
F11=fftshift(F1);
F21=fftshift(F2);
F31=fftshift(F3);
subplot(321);
stem(n,x1)
xlabel('n');
ylabel('x1');
title('p=8,q=2时的时域波形')
subplot(322);
plot(w,abs(F11))
xlabel('w');
ylabel('幅度')
title('p=8,q=2时的幅度谱')
subplot(323);
stem(n,x2)
xlabel('n');
ylabel('x2');
title('p=8,q=4时的时域波形')
subplot(324);
plot(w,abs(F21))
xlabel('w');
ylabel('幅度')
title('p=8,q=4时的幅度谱')
subplot(325);
stem(n,x3)
xlabel('n');
ylabel('x3');
title('p=8,q=8时的时域波形')
subplot(326);
plot(w,abs(F31))
xlabel('w');
ylabel('幅度')
title('p=8,q=8时的幅度谱')