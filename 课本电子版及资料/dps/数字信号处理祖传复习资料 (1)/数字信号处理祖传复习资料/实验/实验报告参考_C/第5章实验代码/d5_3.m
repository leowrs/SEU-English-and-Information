N1=15;
N2=45;
f=[0 0.3 0.3 0.5 0.5 1];
a=[0 0 1 1 0 0];
f15R=fir2(N1-1,f,a,rectwin(N1));
f15B=fir2(N1-1,f,a,blackman(N1));
f15H=fir2(N1-1,f,a,hanning(N1));
[h15R,w15R]=freqz(f15R);
[h15B,w15B]=freqz(f15B);
[h15H,w15H]=freqz(f15H);
h15R=20*log10(abs(h15R));
h15H=20*log10(abs(h15H));
h15B=20*log10(abs(h15B));
w15R=w15R/pi;
w15B=w15B/pi;
w15H=w15H/pi;
figure(1);
plot(w15R,h15R,'r');hold on;
plot(w15B,h15B,'g');hold on;
plot(w15H,h15H,'b');
legend('矩形窗 N=15','布莱克曼窗 N=15','汉宁窗 N=15');
xlabel('归一化频率');
ylabel('幅度/dB');
title('线性相位FIR带通滤波器 幅频响应 N=15');
 axis([0 1 -140 10]);
grid on;
f45R=fir2(N2-1,f,a,rectwin(N2));
f45B=fir2(N2-1,f,a,blackman(N2));
f45H=fir2(N2-1,f,a,hanning(N2));
[h45R,w45R]=freqz(f45R);
[h45B,w45B]=freqz(f45B);
[h45H,w45H]=freqz(f45H);
h45B=20*log10(abs(h45B));
h45H=20*log10(abs(h45H));
h45R=20*log10(abs(h45R));
w45H=w45H/pi;
w45B=w45B/pi;
w45R=w45R/pi;
figure(2);
plot(w45R,h15R,'r');hold on;
plot(w45B,h15B,'g');hold on;
plot(w45H,h15H,'b');
legend('矩形窗 N=45','布莱克曼窗 N=45','汉宁窗 N=45');
xlabel('归一化频率');
ylabel('幅度/dB');
title('线性相位FIR带通滤波器 幅频响应 N=45');
 axis([0 1 -140 10]);
grid on;
