N1=15;
N2=45;
f=[0 0.3 0.3 0.5 0.5 1];
a=[0 0 1 1 0 0];
f15=fir2(N1-1,f,a,hanning(N1));
f45=fir2(N2-1,f,a,hanning(N2));
[h15,w15]=freqz(f15);
[h45,w45]=freqz(f45);
w15=w15/pi;
w45=w45/pi;
fh1=20*log10(abs(h15));
fh2=20*log10(abs(h45));
figure(1);
plot(w15,fh1,'r');
hold on;
plot(w45,fh2,'b');
legend('N=15','N=45');
grid on;
xlabel('归一化频率/pi');ylabel('幅度/dB');title('汉宁窗设计线性相位FIR带通滤波器幅频响应');
axis([0 1 -140 10]);
figure(2);
fa1=angle(h15);
fa2=angle(h45);
plot(w15,fa1,'r');
hold on;
plot(w45,fa2,'b');
hold on;
grid on;
xlabel('归一化频率/pi');ylabel('相位');title('汉宁窗设计线性相位FIR带通滤波器相频响应');
legend('N=15','N=45');
